"""Regression tests for the Stage 3 gap: a generic activity naming an unverified venue.

Rule: a real-world named venue can enter a plan only through a verified research entity.
- activities are EITHER place_id (verified) OR generic_kind (no venue)
- titles are generated by code
- LLM free text may not name places absent from verified research
"""

from __future__ import annotations

import asyncio
import json

import pytest

from app.core.exceptions import ItineraryValidationError
from app.llm.client import StructuredLLM
from app.planning.assembler import assemble_itinerary
from app.planning.named_places import candidate_names, unsupported_names
from app.planning.validator import errors_only, research_evidence, validate_draft
from app.schemas import ItineraryDraft, TravelRequest
from app.services.travel_planner import TravelPlanner
from tests.fakes import (
    FakeSearchProvider,
    ScriptedChatModel,
    goa_draft_json,
    goa_extraction_json,
    goa_items,
    goa_research,
)

EVIDENCE = (
    "Baga Beach in North Goa is known for nightlife. Fort Aguada near Candolim is a 17th-century "
    "Portuguese fort. Fisherman's Wharf serves Goan seafood."
)


# ---------- the detector ----------
@pytest.mark.parametrize(
    "text,flagged",
    [
        ("Visit Imaginary Palace after lunch.", ["Imaginary Palace"]),
        ("Then head to Imaginary Palace.", ["Imaginary Palace"]),
        ("Imaginary Palace is lovely.", ["Imaginary Palace"]),
        ("Try Britto's Restaurant in Baga.", ["Britto's Restaurant"]),
        ("Explore Fort Aguada at sunset.", []),  # sentence-initial verb tolerated
        ("Relax at Baga Beach.", []),
        ("North Goa's beaches are lively.", []),  # possessive
        ("Dinner at Fisherman's Wharf.", []),
        ("A walk around the Portuguese Fort.", []),  # case-insensitive match
        ("Free time near your hotel.", []),
        ("Romantic Goa getaway", []),  # sentence case
    ],
)
def test_unsupported_names(text, flagged):
    assert unsupported_names(text, EVIDENCE) == flagged


def test_single_capitalised_words_are_not_candidates():
    assert candidate_names("Relax. Goan food. Enjoy!") == []


# ---------- validator ----------
def _validate(goa_payload, data, research=None):
    req = TravelRequest.model_validate(goa_payload)
    return validate_draft(ItineraryDraft.model_validate(data), research or goa_research(), req)


def _codes(issues):
    return [i.code for i in errors_only(issues)]


def test_generic_activity_naming_unverified_venue_is_rejected(goa_payload):
    data = goa_draft_json()
    data["days"][2]["activities"][0]["description"] = "Then head to Imaginary Palace for photos."
    issues = _validate(goa_payload, data)
    assert _codes(issues) == ["UNSUPPORTED_NAMED_PLACE"]
    assert "Imaginary Palace" in errors_only(issues)[0].message


def test_naming_a_verified_place_in_free_text_is_allowed(goa_payload):
    data = goa_draft_json()
    data["days"][2]["activities"][0]["description"] = "Walk back towards Baga Beach in the evening."
    assert _codes(_validate(goa_payload, data)) == []


def test_place_only_in_raw_sources_but_not_verified_is_rejected(goa_payload):
    # The attractions source mentions Baga Beach, but if Baga Beach was not verified as an
    # entity, naming it is not allowed.
    research = goa_research()
    research.attractions = [a for a in research.attractions if a.name != "Baga Beach"]
    research.destination_info = None
    data = goa_draft_json()
    data["days"][0]["activities"][0] = {
        "slot": "morning",
        "activity_type": "sightseeing",
        "generic_kind": "free_time",
        "description": "Visit Baga Beach for the morning.",
    }
    assert "UNSUPPORTED_NAMED_PLACE" in _codes(_validate(goa_payload, data, research))


@pytest.mark.parametrize(
    "activity,code",
    [
        ({"slot": "morning", "activity_type": "leisure", "description": "x"}, "MISSING_ACTIVITY_TARGET"),
        (
            {
                "slot": "morning",
                "activity_type": "leisure",
                "place_id": "A1",
                "generic_kind": "free_time",
                "description": "x",
            },
            "CONFLICTING_ACTIVITY_TARGET",
        ),
    ],
)
def test_activity_must_be_place_xor_generic(goa_payload, activity, code):
    data = goa_draft_json()
    data["days"][2]["activities"] = [activity]
    assert code in _codes(_validate(goa_payload, data))


@pytest.mark.parametrize("field", ["summary", "theme", "recommendations", "travel_tips"])
def test_all_llm_free_text_is_checked(goa_payload, field):
    data = goa_draft_json()
    text = "Do not miss the Imaginary Palace."
    if field == "theme":
        data["days"][0]["theme"] = text
    elif field == "summary":
        data["summary"] = text
    else:
        data[field] = [text]
    assert "UNSUPPORTED_NAMED_PLACE" in _codes(_validate(goa_payload, data))


def test_evidence_is_verified_research_only(goa_payload):
    evidence = research_evidence(goa_research(), TravelRequest.model_validate(goa_payload))
    assert "Baga Beach" in evidence and "Bengaluru" in evidence
    assert "Palolem" not in evidence  # appears in a raw search fixture, never verified


# ---------- titles come from code ----------
def test_titles_are_generated_from_verified_names_and_generic_kinds(goa_payload):
    req = TravelRequest.model_validate(goa_payload)
    data = goa_draft_json()
    data["days"][2]["activities"][0]["generic_kind"] = "arrival"
    itin = assemble_itinerary(ItineraryDraft.model_validate(data), goa_research(), req)
    titles = [a.title for d in itin.days for a in d.activities]
    assert titles[:4] == [
        "Visit Baga Beach",
        "Dinner at Fisherman's Wharf",
        "Visit Fort Aguada",
        "Get around by scooter rental",
    ]
    assert titles[4] == "Arrive in Goa" and titles[5] == "Free time"


def test_draft_schema_has_no_title_field():
    data = goa_draft_json()
    data["days"][0]["activities"][0]["title"] = "Visit Imaginary Palace"
    with pytest.raises(ValueError, match="Extra inputs"):
        ItineraryDraft.model_validate(data)


# ---------- end to end: repaired, or rejected ----------
def _planner(make_settings, script, **settings):
    def llm(s):
        return StructuredLLM(
            ScriptedChatModel(script=s), model_name="t", timeout_seconds=5, native_json_schema=False
        )

    return TravelPlanner(
        make_settings(**settings),
        search_provider=FakeSearchProvider(goa_items()),
        research_llm=llm([json.dumps(goa_extraction_json())]),
        planner_llm=llm(script),
    )


def _bad():
    data = goa_draft_json()
    data["days"][2]["activities"][0]["description"] = "Then head to Imaginary Palace."
    return json.dumps(data)


def test_unsupported_name_is_repaired_before_reaching_the_user(make_settings, goa_payload):
    planner = _planner(make_settings, [_bad(), json.dumps(goa_draft_json())])
    resp = asyncio.run(planner.run(TravelRequest.model_validate(goa_payload), "r"))
    assert resp.quality.repair_attempts == 1
    assert "Imaginary Palace" not in resp.itinerary.model_dump_json()


def test_unsupported_name_that_persists_fails_the_request(make_settings, goa_payload):
    planner = _planner(make_settings, [_bad()] * 3, max_repair_attempts=2)
    with pytest.raises(ItineraryValidationError) as info:
        asyncio.run(planner.run(TravelRequest.model_validate(goa_payload), "r"))
    assert info.value.details["errors"] == ["UNSUPPORTED_NAMED_PLACE"]
