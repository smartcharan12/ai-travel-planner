"""Hard rules (errors) and soft checks (warnings) for an optimized draft.

ERRORS make the workflow send the draft back to the LLM with the list of
problems (bounded repair loop). The user never receives a plan with errors.

| code                 | rule |
|----------------------|------|
| DAY_COUNT_MISMATCH   | days must be exactly 1..num_days |
| EMPTY_DAY            | every day needs at least one activity |
| UNKNOWN_PLACE_ID     | every place_id must be a verified research entity |
| HOTEL_AS_ACTIVITY    | hotels are where you sleep, not an activity |
| UNKNOWN_HOTEL_ID     | hotel_id must be a verified hotel |
| TOO_MANY_ACTIVITIES  | defensive re-check of the optimizer's caps |
| MISSING_ACTIVITY_TARGET     | an activity has neither place_id nor generic_kind |
| CONFLICTING_ACTIVITY_TARGET | an activity has both |
| UNSUPPORTED_NAMED_PLACE     | LLM-written text names a place absent from the verified evidence |

WARNINGS are shipped with the plan so the user can judge:

| code                 | meaning |
|----------------------|---------|
| NO_HOTEL_SELECTED    | hotels were found but none was chosen |
| DIETARY_UNVERIFIED   | user has dietary needs; a scheduled restaurant's sources don't confirm them |
| LOW_GROUNDING        | under half the activities reference a researched place |

Named venues can enter a plan only through a verified ``place_id``: titles are
generated by code, and free text (descriptions, themes, summary, tips,
recommendations) is checked by ``named_places.unsupported_names`` against
verified research only (entities, verified overview, request place names).
Names written in lower case are not detected; see
``named_places`` for the documented limits.
"""

from __future__ import annotations

from app.planning.named_places import build_evidence, unsupported_names
from app.planning.rules import MAX_ACTIVITIES_BY_PACE
from app.research.text import contains_phrase
from app.schemas import (
    IssueSeverity,
    ItineraryDraft,
    ResearchResult,
    Restaurant,
    TravelRequest,
    ValidationIssue,
)

_DIET_KEYWORDS = {
    "vegetarian": ("vegetarian", "pure veg"),  # not bare "veg": it also matches "non veg"
    "vegan": ("vegan", "plant based"),
    "jain": ("jain",),
    "halal": ("halal",),
    "gluten_free": ("gluten free", "gluten-free"),
    "no_seafood": (),  # can't be confirmed from text; always unverified
}


def _error(code: str, message: str, day: int | None = None) -> ValidationIssue:
    return ValidationIssue(severity=IssueSeverity.ERROR, code=code, message=message, day_number=day)


def _warning(code: str, message: str, day: int | None = None) -> ValidationIssue:
    return ValidationIssue(severity=IssueSeverity.WARNING, code=code, message=message, day_number=day)


def _diet_confirmed(restaurant: Restaurant, diet: str) -> bool:
    text = " ".join(
        filter(None, [restaurant.name, restaurant.cuisine, restaurant.dietary_notes, restaurant.description])
    )
    return any(contains_phrase(text, kw) for kw in _DIET_KEYWORDS.get(diet, ()))


def research_evidence(research: ResearchResult, request: TravelRequest) -> str:
    """Text a place name may legitimately come from: VERIFIED research and the request.

    Raw search-result text is deliberately excluded: a place merely mentioned
    in a source, but not verified as an entity, cannot be scheduled or named.
    """
    parts: list[str | None] = [request.destination, request.origin_city]
    for e in research.entity_index().values():
        parts += [e.name, e.area, getattr(e, "description", None), getattr(e, "cuisine", None)]
    if research.destination_info:
        parts += [research.destination_info.summary, *research.destination_info.local_tips]
    return build_evidence(parts)


def _named_place_errors(draft: ItineraryDraft, evidence: str) -> list[ValidationIssue]:
    issues: list[ValidationIssue] = []

    def check(text: str, where: str, day: int | None = None) -> None:
        for name in unsupported_names(text, evidence):
            issues.append(
                _error(
                    "UNSUPPORTED_NAMED_PLACE",
                    f"{where} mentions '{name}', which is not a verified place. Use a place_id from "
                    "ALLOWED PLACES, or describe it generically in sentence case.",
                    day,
                )
            )

    check(draft.title, "The title")
    check(draft.summary, "The summary")
    for day in draft.days:
        check(day.theme, f"Day {day.day_number} theme", day.day_number)
        for i, activity in enumerate(day.activities, start=1):
            check(activity.description, f"Day {day.day_number} activity {i}", day.day_number)
    for field in ("recommendations", "travel_tips"):
        for line in getattr(draft, field):
            check(line, field.replace("_", " ").capitalize())
    return issues


def validate_draft(
    draft: ItineraryDraft, research: ResearchResult, request: TravelRequest
) -> list[ValidationIssue]:
    entities = research.entity_index()
    hotel_ids = {h.id for h in research.hotels}
    issues: list[ValidationIssue] = []

    expected = list(range(1, request.num_days + 1))
    actual = [d.day_number for d in draft.days]
    if actual != expected:
        issues.append(_error("DAY_COUNT_MISMATCH", f"Days must be numbered {expected}, got {actual}."))

    cap = MAX_ACTIVITIES_BY_PACE[request.preferences.pace]
    total = grounded = 0
    for day in draft.days:
        n = day.day_number
        if not day.activities:
            issues.append(_error("EMPTY_DAY", f"Day {n} has no activities.", n))
        if len(day.activities) > cap:
            issues.append(_error("TOO_MANY_ACTIVITIES", f"Day {n} has {len(day.activities)} > {cap}.", n))
        for i, activity in enumerate(day.activities, start=1):
            total += 1
            pid = activity.place_id
            if pid is None and activity.generic_kind is None:
                issues.append(
                    _error(
                        "MISSING_ACTIVITY_TARGET",
                        f"Day {n} activity {i}: set place_id (a named place) "
                        "or generic_kind (no specific place).",
                        n,
                    )
                )
                continue
            if pid is not None and activity.generic_kind is not None:
                issues.append(
                    _error(
                        "CONFLICTING_ACTIVITY_TARGET",
                        f"Day {n} activity {i}: set only one of place_id and generic_kind.",
                        n,
                    )
                )
                continue
            if pid is None:
                continue
            if pid not in entities:
                issues.append(_error("UNKNOWN_PLACE_ID", f"Day {n}: '{pid}' is not in ALLOWED PLACES.", n))
                continue
            if pid in hotel_ids:
                issues.append(_error("HOTEL_AS_ACTIVITY", f"Day {n}: hotel {pid} used as an activity.", n))
                continue
            grounded += 1
            entity = entities[pid]
            if isinstance(entity, Restaurant):
                for diet in request.preferences.dietary:
                    if not _diet_confirmed(entity, diet.value):
                        issues.append(
                            _warning(
                                "DIETARY_UNVERIFIED",
                                f"Day {n}: sources don't confirm {entity.name} suits '{diet.value}'. "
                                "Check before going.",
                                n,
                            )
                        )

    if draft.hotel_id is not None and draft.hotel_id not in hotel_ids:
        issues.append(_error("UNKNOWN_HOTEL_ID", f"hotel_id '{draft.hotel_id}' is not a verified hotel."))
    if draft.hotel_id is None and research.hotels:
        issues.append(_warning("NO_HOTEL_SELECTED", "Hotels were found but none was selected."))
    issues += _named_place_errors(draft, research_evidence(research, request))
    if total and grounded / total < 0.5:
        issues.append(
            _warning("LOW_GROUNDING", f"Only {grounded} of {total} activities reference a researched place.")
        )
    return issues


def errors_only(issues: list[ValidationIssue]) -> list[ValidationIssue]:
    return [i for i in issues if i.severity == IssueSeverity.ERROR]
