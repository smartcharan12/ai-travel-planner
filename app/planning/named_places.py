"""Detect place names in LLM-written text that verified research does not support.

Why this exists: activities are now structured (a verified ``place_id`` or a
``generic_kind``) and titles are generated by code. The model still writes a
few free-text fields (descriptions, day themes, summary, tips), and those
could mention a venue the research never found ("…then head to Imaginary
Palace").

How it works (deterministic, no word lists of "bad" places):

1. Find candidate proper names: runs of 2+ capitalised words, allowing small
   connectors inside ("Fort of Good Hope", "Café de Paris"). Possessive
   "'s" is stripped ("North Goa's" -> "North Goa").
2. A candidate is *supported* if it appears (case/accent/punctuation-
   insensitive, whole words) in the evidence: verified entity names/areas,
   destination info, the request's place names, and the text of the search
   results the research came from.
3. If a run starts a sentence, its first word may just be a capitalised verb
   ("Explore Fort Aguada"), so the run also counts as supported when the
   remainder is supported.

Known limits (documented in docs/10_hallucination_control.md):
- names written in lower case are not detected;
- a capitalised generic phrase that is not in the evidence ("Sunset Cruise")
  is flagged, which costs a repair round. The prompt asks for sentence case
  to keep this rare;
- single capitalised words are ignored (too ambiguous: "Relax", "Goan").
"""

from __future__ import annotations

import re
from collections.abc import Iterable

from app.research.text import contains_phrase

_TOKEN = re.compile(r"[^\W\d_][\w'’\-]*|[.!?;:\n]")
_SENTENCE_END = {".", "!", "?", ";", ":", "\n"}
_CONNECTORS = {"of", "de", "da", "del", "di", "du", "la", "le", "the", "and", "&"}


def _clean(token: str) -> str:
    for suffix in ("'s", "’s"):
        if token.endswith(suffix):
            return token[: -len(suffix)]
    return token


def candidate_names(text: str) -> list[tuple[str, bool]]:
    """Return (name, starts_sentence) for each run of 2+ capitalised words (raw spelling)."""
    found: list[tuple[str, bool]] = []
    run: list[str] = []
    run_starts_sentence = False
    at_sentence_start = True

    def close_run() -> None:
        while run and run[-1].lower() in _CONNECTORS:
            run.pop()
        if sum(1 for w in run if w[0].isupper()) >= 2:
            found.append((" ".join(run), run_starts_sentence))
        run.clear()

    for token in _TOKEN.findall(text):
        if token in _SENTENCE_END:
            close_run()
            at_sentence_start = True
            continue
        if token[0].isupper():
            if not run:
                run_starts_sentence = at_sentence_start
            run.append(token)
        elif run and token.lower() in _CONNECTORS:
            run.append(token)
        else:
            close_run()
        at_sentence_start = False
    close_run()
    return found


def _supported(phrase: str, evidence: str) -> bool:
    """Match the raw phrase or its possessive-free form ("North Goa's" -> "North Goa")."""
    variants = {phrase, " ".join(_clean(w) for w in phrase.split())}
    return any(contains_phrase(evidence, v) for v in variants)


def unsupported_names(text: str, evidence: str) -> list[str]:
    """Candidate names in ``text`` that the ``evidence`` text does not contain."""
    flagged: list[str] = []
    for name, starts_sentence in candidate_names(text):
        if _supported(name, evidence):
            continue
        if starts_sentence:
            # The first word may be a capitalised verb: "Explore Fort Aguada".
            remainder = name.split(" ", 1)[1]
            while remainder.split(" ", 1)[0].lower() in _CONNECTORS and " " in remainder:
                remainder = remainder.split(" ", 1)[1]
            if _supported(remainder, evidence):
                continue
            name = remainder if sum(1 for w in remainder.split() if w[0].isupper()) >= 2 else name
        if name not in flagged:
            flagged.append(name)
    return flagged


def build_evidence(parts: Iterable[str | None]) -> str:
    return "\n".join(p for p in parts if p)
