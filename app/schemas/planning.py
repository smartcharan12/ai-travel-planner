"""Structured-output contract for the itinerary-planning LLM call.

``ItineraryDraft`` is what Gemini returns. It is deliberately *smaller* than
the final ``Itinerary``:

- no titles, prices, dates or areas: code fills those from verified research and
  the request (``app/planning/assembler.py``), so the model has no field in
  which to invent a number;
- places are referenced only by id (``A1``, ``R2``...) from the verified list;
- limits are generous (8 activities/day) so a slightly over-full day is
  trimmed by the optimizer instead of failing schema validation.
"""

from __future__ import annotations

from pydantic import Field

from app.schemas.common import StrictModel
from app.schemas.itinerary import ActivityType, GenericActivity, TimeSlot


class DraftActivity(StrictModel):
    """One scheduled item. Set EXACTLY ONE of ``place_id`` or ``generic_kind``.

    There is no ``title`` field: titles are generated by code from the
    verified place name or the generic kind, so the model has no free-text
    slot in which to introduce an unverified venue name.
    """

    slot: TimeSlot
    activity_type: ActivityType
    place_id: str | None = Field(default=None, description="Id from ALLOWED PLACES for a named venue.")
    generic_kind: GenericActivity | None = Field(
        default=None, description="For activities with no specific venue (free time, check-in, ...)."
    )
    description: str = Field(
        max_length=300, description="One sentence. Do not name any place other than this activity's place."
    )


class DraftDay(StrictModel):
    day_number: int = Field(ge=1)
    theme: str = Field(max_length=120)
    activities: list[DraftActivity] = Field(max_length=8)


class ItineraryDraft(StrictModel):
    title: str = Field(max_length=150)
    summary: str = Field(max_length=1000)
    hotel_id: str | None = Field(description="Id of a hotel from ALLOWED PLACES, or null.")
    days: list[DraftDay] = Field(min_length=1, max_length=14)
    recommendations: list[str] = Field(default_factory=list, max_length=10)
    travel_tips: list[str] = Field(default_factory=list, max_length=10)
    uncertainty_notes: list[str] = Field(default_factory=list, max_length=10)
